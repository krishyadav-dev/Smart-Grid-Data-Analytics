def faults(results: Path) -> dict:
    s = load(results / "layer3" / "fault" / "summary.json")
    live_p = results / "layer3" / "fault" / "live" / "summary.json"
    live = load(live_p) if live_p.exists() else None
    det, typ, zone = s["detection"], s["type"], s["zone"]
    out = {
        "available": True,
        "source": "results/layer3/fault/summary.json",
        "window": f"test half: {s['half']['n_faults']} faults + {s['half']['n_quiet_windows']} quiet windows "
                  f"({s['half']['documents']} burst documents), scored once with frozen parameters",
        "params": s["params"], "params_commit": s["params_commit"], "relay": s["relay"],
        "detection": {**_pick(det, "alerts", "tp_alerts", "false_positives", "precision", "recall", "f1",
                              "quiet_windows_with_alarm", "faults_with_more_than_one_alert"),
                      "per_type": {k: v["recall"] for k, v in det["per_type"].items()},
                      "per_rf_class": det["per_rf_class"], "per_bus": det["per_bus"]},
        "no_dip": s["no_dip"],
        "type": {"accuracy_4class": typ["accuracy_4class"],
                 "accuracy_merged_two_phase": typ["accuracy_merged_two_phase"],
                 "per_type_accuracy": typ["per_type_accuracy"],
                 "per_rf_class_accuracy": typ["per_rf_class_accuracy"],
                 "confusion_true_rows": transpose(typ["confusion_true_by_pred"])},
        "zone": {"accuracy": zone["accuracy"], "baseline": zone["baseline_deepest_dt_accuracy"],
                 "per_true_zone": zone["per_true_zone"], "per_type": zone["per_type"],
                 "baseline_per_type": zone["baseline_per_type"], "per_rf_class": zone["per_rf_class"],
                 "error_direction": zone.get("error_direction"),
                 "baseline_error_direction": zone.get("baseline_error_direction"),
                 "bus_level_accuracy": zone.get("bus_level_accuracy"),
                 "confusion_true_rows": transpose(zone["confusion_true_by_pred"])},
        "timing": s.get("timing"),
        "flat_baseline": s.get("flat_baseline"),
        "splits": s.get("splits"),
        "unbalance_feeder_head_2024": s.get("unbalance_feeder_head_2024"),
        "live": None,
    }
    if live:
        out["live"] = {"source": "results/layer3/fault/live/summary.json", "passed": live.get("passed"),
                       "plan": live["plan"],
                       "pooled": {k: _pick(v, "runs", "alarm_latency_ms", "events", "faults", "quiet_windows",
                                           "alarms", "bursts", "bursts_expected", "telemetry", "telemetry_expected",
                                           "gap_flagged_messages", "live_false_alarms", "live_batch_identical",
                                           "wall_s")
                                  for k, v in live["pooled"].items()}}
    return out


def fault_events(results: Path, config_dir: Path) -> dict:
    """Engine events of the test half, joined to the true fault where the
    (git-ignored) fault set is present."""
    ev_path = results / "layer3" / "fault" / "summary_events.parquet"
    if not ev_path.exists():
        return missing(ev_path, "python scripts/run_layer3_fault.py")
    try:
        import pandas as pd
        ev = pd.read_parquet(ev_path)
    except ImportError:                                  # pyarrow not installed
        return missing(ev_path, "pip install pyarrow (requirements.txt)")
    cols = ["onset", "n_meters", "ftype", "type_source", "zone", "zone_node", "zone_set", "baseline_zone",
            "baseline_bus", "residual_pct", "duration_ms", "clearing_ms", "clearing_source", "i_head_max_a",
            "t_idmt_phase_s", "t_expected_clear_s", "head_detected", "matched"]
    ev = ev[[c for c in cols if c in ev.columns]].copy()

    truth_path = results / "faults_2024" / "fault_events.parquet"
    truth_available = truth_path.exists()
    if truth_available:
        import yaml
        tr = pd.read_parquet(truth_path)
        zdoc = yaml.safe_load((config_dir / "zones.yaml").read_text(encoding="utf-8"))
        bus_zone = {str(b): z["id"] for z in zdoc["zones"] for b in z["buses"]}
        # Columns as read by evaluate.load_labels (the one Layer 3 module allowed to read labels).
        keep = [c for c in ("event_id", "bus", "ftype", "phases", "rf_ohm", "rf_model") if c in tr.columns]
        tr = tr[keep].rename(columns={"event_id": "matched", "bus": "true_bus", "ftype": "true_ftype"})
        if "rf_model" in tr.columns and "rf_ohm" in tr.columns:     # same rule as evaluate.load_labels
            tr["rf_class"] = [("arc" if m == "arc" else ("" if pd.isna(r) else f"{r:g}"))
                              for m, r in zip(tr.rf_model, tr.rf_ohm)]
        tr["true_bus"] = tr["true_bus"].astype(str)
        tr["true_zone"] = tr["true_bus"].map(bus_zone)
        ev = ev.merge(tr, on="matched", how="left")
        ev["zone_hit"] = ev["zone"] == ev["true_zone"]
        ev["type_hit"] = ev["ftype"] == ev["true_ftype"]
    ev = ev.astype(object).where(ev.notna(), None)
    return {"available": True, "source": str(ev_path.relative_to(results.parent)),
            "truth_available": truth_available,
            "truth_how": None if truth_available else "python scripts/run_faults.py (writes results/faults_2024/)",
            "events": ev.to_dict(orient="records")}


