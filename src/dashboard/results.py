"""Report-mode views of the frozen Layer 3 results (plan.md §4.2).

Each function reads files written by Layers 1-3 and returns a chart-ready dict.
Nothing is recomputed: values are selected and re-shaped only.  Committed
summaries (``results/**/summary.json``) are always present; git-ignored detail
files (parquet / npz, regenerated by the Layer 3 scripts) are optional, and a
view that needs one reports ``{"available": false, "how": "<script>"}``.

Note on confusion matrices: ``evaluate.py`` writes ``confusion_true_by_pred``
as ``{predicted: {true: n}}`` (evaluate.py line 216; the column sums equal the
true-class counts in ``per_true_zone`` / ``per_type_accuracy``).  The views
below return it transposed as ``{true: {predicted: n}}`` under
``confusion_true_rows``.
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path
from typing import Any, Optional

# Same constant as src/analytics/unbalance.py (that module imports numpy only, but keep
# the dashboard's report path free of analytics imports); tests check they agree.
VU_LIMIT_PCT = 2.0


def _read(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


@lru_cache(maxsize=32)
def _json(path: Path, mtime: float) -> dict:          # mtime in the key: re-read after a re-run
    return _read(path)


def load(path: Path) -> dict:
    return _json(path, path.stat().st_mtime)


def missing(path: Path, how: str) -> dict:
    return {"available": False, "file": str(path), "how": how}


def transpose(pred_true: dict) -> dict:
    """{pred: {true: n}} -> {true: {pred: n}}."""
    out: dict[str, dict[str, int]] = {}
    for p, col in pred_true.items():
        for t, n in col.items():
            out.setdefault(t, {})[p] = n
    return out


def _pick(d: dict, *keys: str) -> dict:
    return {k: d[k] for k in keys if k in d}


