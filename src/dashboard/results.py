def thermal(results: Path) -> dict:
    s = load(results / "layer3" / "thermal" / "summary.json")
    ref, met = s["reference"], s["metrics"]
    models = {}
    for name, m in met["main"]["models"].items():
        models[name] = {"hot_spot_pooled": m["hot_spot"]["pooled"], "hot_spot_per_dt": m["hot_spot"]["per_dt"],
                        "loss_of_life": m.get("loss_of_life"), "events": m.get("events")}
    lstm_sel = s.get("lstm_selection", {})
    return {
        "available": True,
        "source": "results/layer3/thermal/summary.json",
        "window": ref["definition"].get("test_window"),
        "acceptance": _pick(s["acceptance"], "passes", "expected_theta_h_c", "result", "theta_h_by_dt", "note"),
        "reference_definition": ref["definition"],
        "reference": {ps: _pick(ref[ps], "per_dt", "event_dt_days_total", "loss_of_life_all_dts", "peak_theta_h",
                                "peak_rise")
                      for ps in ("main", "table_e1") if ps in ref},
        "load_temperature_correlation": ref.get("load_temperature_correlation"),
        "thresholds_c": [98, 120, 140],
        "forecast": {"definitions": met.get("definitions"), "models": models,
                     "bootstrap": met["main"].get("bootstrap"),
                     "seed_spread_hot_spot_rmse_k": met["main"].get("seed_spread_hot_spot_rmse_k"),
                     "load_k_p": {k: v["pooled"] for k, v in met.get("load_k_p", {}).items()},
                     "frozen": s.get("test_run", {}).get("frozen"),
                     "candidates": {k: _pick(v, "variant", "layers", "units", "n_parameters", "mean_hot_spot_rmse_k")
                                    for k, v in lstm_sel.get("candidates", {}).items()},
                     "baselines_april": {k: _pick(v, "mean_hot_spot_rmse_k", "explained_variance")
                                         for k, v in lstm_sel.get("baselines_april", {}).items()},
                     "chosen": lstm_sel.get("chosen"),
                     "honesty": "The LSTM hot-spot forecast is not better than persistence (bootstrap 95 % CI of "
                                "RMSE difference includes 0)."},
        "addendum_i": s.get("addendum_i"),
    }


