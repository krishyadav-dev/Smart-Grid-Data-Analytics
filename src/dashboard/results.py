def ingestion(results: Path) -> dict:
    benches = sorted(results.glob("bench_*.json"))
    if not benches:
        return missing(results / "bench_*.json", "python scripts/bench_ingestion.py")
    runs = []
    for p in benches:
        d = load(p)
        rows = []
        for r in d.get("results", []):
            rows.append({k: r.get(k) for k in ("playback_speed", "run", "wall_s_per_step", "poll_interval_s",
                                               "speed_achieved", "expected_messages", "accepted",
                                               "loss_fraction", "duplicates_rejected", "gap_messages",
                                               "throughput_msgs_per_s", "latency_ms", "gateway_poll_cycle_max")
                         if k in r}
                        | {"loss_totals": _loss_totals(r.get("loss_accounting"))})
        runs.append({"file": p.name, "created_utc": d.get("created_utc"),
                     "metadata": _pick(d.get("metadata", {}), "profiles", "simulated_window", "steps", "meters",
                                       "speeds", "gateway_poll_interval_s", "os"),
                     "results": rows, "asserted": d.get("asserted")})
    return {"available": True, "runs": runs}


def _loss_totals(la: Optional[dict]) -> Optional[dict[str, Any]]:
    if not la or "per_meter" not in la:
        return None
    lost = sum(v.get("lost", 0) for v in la["per_meter"].values())
    flagged = sum(v.get("flagged", 0) for v in la["per_meter"].values())
    return {"lost": lost, "flagged": flagged}
